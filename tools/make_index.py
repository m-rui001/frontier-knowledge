def field_of(wid):
    src = open(f"kb/w/{wid}/summary.typ", encoding="utf-8").read()
    m = re.search(r'title:\s*"([^"]*)"', src)
    return m.group(1) if m else wid


def ratio_of(wid):
    src = open(f"kb/w/{wid}/summary.typ", encoding="utf-8").read()
    m = re.search(r'ratio:\s*"([^"]*)"', src)
    return m.group(1) if m else ""


