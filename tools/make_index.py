def field_of(wid):
    src = open(f"kb/w/{wid}/summary.typ", encoding="utf-8").read()
    m = re.search(r'title:\s*"([^"]*)"', src)
    return m.group(1) if m else wid


def ratio_of(wid):
    src = open(f"kb/w/{wid}/summary.typ", encoding="utf-8").read()
    m = re.search(r'ratio:\s*"([^"]*)"', src)
    return m.group(1) if m else ""


def main():
    have = {os.path.basename(d) for d in glob.glob("kb/w/*") if os.path.isdir(d)}
    rows = [(i, wid, dom) for i, (wid, dom) in enumerate(ORDER, 1) if wid in have]

    # ---- INDEX.md ----
    out = ["# 索引\n", f"{len(rows)} 篇，按主题相邻排列。每篇一个目录：`kb/w/<id>/`，"
           "里面有 `summary.typ`（源）、`summary.pdf`（成品）、`source.txt`（原文摘要与元数据）。\n",
           "| # | 领域 | 标题 | 压缩 | id |", "|---|---|---|---|---|"]
    for i, wid, dom in rows:
        out.append(f"| {i} | {dom} | {field_of(wid)} | {ratio_of(wid)} | {wid} |")
    open("INDEX.md", "w", encoding="utf-8").write("\n".join(out) + "\n")

    # ---- 領域地圖（單頁） ----
    fc = json.load(open("meta/field_counts.json", encoding="utf-8"))
    m = ['#import "../typst/lib.typ": *\n',
         '#set page(paper: "a4", margin: (x: 22mm, y: 20mm))\n',
         '#set text(font: ("Microsoft YaHei",), lang: "zh", size: 10pt)\n',
         '#set par(leading: .8em, spacing: .55em, justify: true, first-line-indent: (amount: 2em, all: true))\n',
         '#text(size: 16pt, weight: "bold")[领域地图]\n#v(.7em)\n',
         '三年窗口（2023-11-22 至 2026-11-22）里，OpenAlex 全库收了四千五百多万条作品。'
         '下表第二列是各领域在这个窗口内的总量，用来看体量差距；第三列是这套笔记在那个方向上挑了几篇。\n#v(.4em)\n',
         '数字之间的差距有好几个量级：医学与生物加起来占半壁，这里只挑了十几篇，比例上被严重低估；'
         '数学与理论物理产出量小，但单篇分量常常更重。取样偏差就在这里，读到哪一行觉得不对劲，那一行就是该自己去补的地方。\n#v(.6em)\n',
         '#set par(first-line-indent: 0em)\n',
         '#table(\n  columns: (auto, auto, auto, 1fr),\n  stroke: none,\n  inset: (x: 2.4mm, y: 1.6mm),\n  align: (left, right, right, left),\n',
         '  table.header([*领域*], [*窗口内作品数*], [*收录*], [*篇目*]),\n',
         '  table.hline(stroke: .9pt + ink),\n']
    for zh, fid, pat in MAP_ROWS:
        n = (fc.get(fid) or {}).get("n", 0) if fid != "-" else None
        nstr = "—" if n is None else f"{n:,}"
        sel = [wid for _, wid, dom in rows if re.search(pat, dom)]
        titles = "、".join(field_of(w) for w in sel[:2])
        if len(sel) > 2:
            titles += f" 等 {len(sel)} 篇"
